    echo "║   ██╔══██╗██╔════╝██╔══██╗██║     ██╔═══██╗╚██╗ ██╔╝      ║"
    echo "║   ██║  ██║█████╗  ██████╔╝██║     ██║   ██║ ╚████╔╝       ║"
    echo "║   ██║  ██║██╔══╝  ██╔═══╝ ██║     ██║   ██║  ╚██╔╝        ║"
    echo "║   ██████╔╝███████╗██║     ███████╗╚██████╔╝   ██║         ║"
    echo "║   ╚═════╝ ╚══════╝╚═╝     ╚══════╝ ╚═════╝    ╚═╝         ║"
