#!/bin/bash
#===============================================================================
# WURM-TOOLS Application Deployment Script
# For Ubuntu 22.04/24.04 LTS on OVH VPS
#
# This script:
# - Clones or updates the application
# - Installs dependencies
# - Sets up environment configuration
# - Imports database schema
# - Builds and starts the application
#
# Usage: sudo bash 03-deploy-app.sh
#===============================================================================

set -e  # Exit on error

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
NC='\033[0m' # No Color

# Configuration
APP_DIR="/var/www/wurm-tools"
REPO_URL="${REPO_URL:-https://github.com/Yarpii/WURM-TOOLS.git}"
BRANCH="${BRANCH:-main}"
DOMAIN="${DOMAIN:-blackforge.tools}"

#===============================================================================
# Helper Functions
#===============================================================================

log_info() {
    echo -e "${BLUE}[INFO]${NC} $1"
}

log_success() {
    echo -e "${GREEN}[SUCCESS]${NC} $1"
}

log_warning() {
    echo -e "${YELLOW}[WARNING]${NC} $1"
}

log_error() {
    echo -e "${RED}[ERROR]${NC} $1"
}

